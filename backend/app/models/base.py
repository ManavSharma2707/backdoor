"""Declarative base, naming convention and the tenancy helpers every model uses."""

import uuid
from collections.abc import Sequence
from datetime import datetime

from sqlalchemy import (
    CheckConstraint,
    DateTime,
    ForeignKey,
    ForeignKeyConstraint,
    MetaData,
    Numeric,
    UniqueConstraint,
    func,
    text,
)
from sqlalchemy.dialects.postgresql import UUID
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

# Composite aware tokens: several tenant scoped constraints share the same first column.
NAMING_CONVENTION = {
    "ix": "ix_%(table_name)s_%(column_0_N_name)s",
    "uq": "uq_%(table_name)s_%(column_0_N_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_N_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}

TZ = DateTime(timezone=True)
MONEY = Numeric(14, 2)
PRICE = Numeric(12, 2)
UNIT_COST = Numeric(12, 4)
QTY = Numeric(14, 3)

EMPTY_OBJECT = text("'{}'::jsonb")
EMPTY_ARRAY = text("'[]'::jsonb")
EMPTY_TEXT_ARRAY = text("'{}'::text[]")


class Base(DeclarativeBase):
    metadata = MetaData(naming_convention=NAMING_CONVENTION)


class IdMixin:
    """UUID primary key generated by the database (and by Python when built in memory)."""

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        primary_key=True,
        default=uuid.uuid4,
        server_default=text("gen_random_uuid()"),
        sort_order=-100,
    )


class TenantMixin:
    """Every tenant owned table carries `tenant_id`."""

    tenant_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), ForeignKey("tenants.id"), nullable=False, sort_order=-90
    )


class CreatedAtMixin:
    created_at: Mapped[datetime] = mapped_column(
        TZ, nullable=False, server_default=func.now(), sort_order=900
    )


class UpdatedAtMixin:
    """Maintained by the `set_updated_at()` trigger, so no ORM onupdate is needed."""

    updated_at: Mapped[datetime] = mapped_column(
        TZ, nullable=False, server_default=func.now(), sort_order=901
    )


def composite_fk(column: str, parent: str) -> ForeignKeyConstraint:
    """Tenant scoped foreign key `(tenant_id, column) -> parent(tenant_id, id)`.

    The parent must expose `tenant_unique()`. A row can then never point at another tenant's
    data. When `column` is nullable the constraint is skipped for NULL (MATCH SIMPLE).
    """
    return ForeignKeyConstraint(["tenant_id", column], [f"{parent}.tenant_id", f"{parent}.id"])


def tenant_unique() -> UniqueConstraint:
    """`UNIQUE (tenant_id, id)`, the target of composite foreign keys."""
    return UniqueConstraint("tenant_id", "id")


def enum_check(
    column: str, values: Sequence[str], *, nullable: bool = False, name: str | None = None
) -> CheckConstraint:
    """`CHECK (column IN (...))`, our replacement for native enum types."""
    listed = ", ".join(f"'{value}'" for value in values)
    quoted = f'"{column}"'  # some column names, such as window, are reserved words
    condition = f"{quoted} IN ({listed})"
    if nullable:
        condition = f"{quoted} IS NULL OR {condition}"
    return CheckConstraint(condition, name=name or f"{column}_valid")
